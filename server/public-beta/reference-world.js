'use strict';
// Connection-local display projection. The saved account and native template
// stay immutable; ordinary accounts never enter this local-reference branch.
const crypto=require('node:crypto'),W=require('../player-profile-wire'),Snapshot=require('../player-profile-snapshot'),P=require('../battle-protobuf'),R=require('../roledata');
const UID=110011,PLAYER_ID=11001101,WORLD_OFF=288432,WORLD_IDS=Object.freeze([20032,20034]);
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
function reference(account){
 const identity=account?.publicBetaIdentity;if(identity?.version!==2)return false;
 if(account.uid!==UID||account.playerId!==PLAYER_ID||identity.uid!==UID||identity.playerId!==PLAYER_ID)throw Error('Local reference world identity mismatch');
 return true;
}
function world(value){if(!WORLD_IDS.includes(value))throw Error('Unsupported local reference world');return value;}
function projectProfile(frame,account,worldId){
 if(!reference(account))return frame;world(worldId);const profile=W.unpack(frame,account);
 if(!WORLD_IDS.includes(profile.serverId))throw Error('Unverified local reference profile world');
 if(profile.serverId===worldId)return frame;
 profile.header.writeUInt32LE(worldId,12);profile.serverId=worldId;profile.fields=P.set(profile.fields,2,worldId);return W.pack(profile);
}
function projectAccount(account,worldId){
 if(!reference(account))return account;world(worldId);
 if(!account.profileSnapshot)throw Error('Local reference profile is missing');
 // The new reference account observes generated bytes. Rebasing old import
 // provenance would misidentify its historical source and is forbidden.
 if(account.profileSnapshot.source!==undefined)throw Error('Local reference profile is not a fresh observation');
 Snapshot.validate(account.profileSnapshot,account);const old=Buffer.from(account.profileSnapshot.frameBase64,'base64'),frame=projectProfile(old,account,worldId);
 if(frame===old)return account;
 const projected={...account,profileSnapshot:{...account.profileSnapshot,frameBase64:frame.toString('base64'),sha256:sha(frame)}};Snapshot.validate(projected.profileSnapshot,projected);return projected;
}
function patchRole(blob,account,worldId){
 if(!reference(account))return blob;world(worldId);
 if(!Buffer.isBuffer(blob)||blob.length!==288458||blob.readUInt32LE(0)!==288540||blob.readUInt16LE(8)!==1013||blob[12]!==1||blob.readUInt32LE(22)!==PLAYER_ID||blob.readUInt32LE(26)!==UID)throw Error('Local reference role identity or layout mismatch');
 if(!WORLD_IDS.includes(blob.readUInt32LE(WORLD_OFF)))throw Error('Unverified local reference role world');
 if(blob.readUInt32LE(WORLD_OFF)===worldId)return blob;const out=Buffer.from(blob);out.writeUInt32LE(worldId,WORLD_OFF);return out;
}
function projectRoleFrame(frame,account,worldId){
 if(!reference(account))return frame;world(worldId);
 if(!Buffer.isBuffer(frame)||frame.length<12)throw Error('Invalid local reference role frame');
 if(frame.readUInt16LE(8)===1013)return patchRole(frame,account,worldId);
 if(frame.readUInt16LE(8)!==1166||frame.readUInt32LE(0)!==frame.length)throw Error('Invalid local reference role wrapper');
 const blob=R.inflate(frame.subarray(12)),out=patchRole(blob,account,worldId);return out===blob?frame:R.buildFrame(out,frame).frame;
}
module.exports={projectAccount,projectProfile,patchRole,projectRoleFrame,UID,PLAYER_ID,WORLD_OFF,WORLD_IDS};
